"""Staff roll: add the English translation / Trinea DX credit (struktured labs).
The three rolls live in bank $CA, reached only through the 3-entry pointer table at $CA:0000 ($C0:EB4E,
LDA $CA0000,x with 16-bit X). Text: '$' = new line, '&' at line start + 1 byte = end (fade after n*16 frames), '%' and '+' are roll control bytes (kept).
Layout written here: table + roll 2 (full roll) + roll 0 at $CA:0006 (must end before $CA:1B02, the end of the
original data), roll 1 moved to the zero padding at the end of the bank ($CA:F740-$CA:FFFF, unused).
Output: build/gen/credits.asm (+ .bin files)."""
import os,struct
R=open(os.environ['TRINEA_ROM'],'rb').read()
B=0x0A0000; GEN='build/gen'
ptr=[struct.unpack('<H',R[B+2*i:B+2*i+2])[0] for i in range(3)]
def roll(a):  # parse like $C0:EB59: at a line start '%' and '+' are 1-byte commands, '&' n ends; else a text line up to '$'
    i=B+a
    while True:
        c=R[i]
        if c==0x26: return bytearray(R[B+a:i+2])
        if c in (0x25,0x2B): i+=1; continue
        i=R.index(b'$',i)+1
rolls=[roll(a) for a in ptr]
def ins(r,anchor,text,after=True):
    i=r.index(anchor); assert r.count(anchor)==1, anchor
    j=i+len(anchor) if after else i
    r[j:j]=text
# full roll (index 2, mixed case, names indented 2): after the Japan Art Media special thanks
ins(rolls[2],b'  Orie Takahashi$$$',b'[ ENGLISH TRANSLATION ]$  struktured labs$  (struktured)$$$[ TRINEA DX ]$  struktured labs$$$'
    b'[ ENGLISH SUBTITLES ]$  eadmaster (RetroSubs)$  Sara scenario and opening$$$')
# per-scenario rolls (indices 0/1, upper case, centred in 31 columns): before the closing TRINEA card
def c(s,w=31): p=(w-len(s))//2; return (' '*p+s).encode()
for k,anchor in ((0,b'$$$          [ TRINEA ]           $'),(1,b'$$$$$$$$          [ TRINEA ]$')):
    pad=k==0
    lines=[c('[ ENGLISH TRANSLATION ]'),c('STRUKTURED LABS'),c('(STRUKTURED)'),b'',c('[ TRINEA DX ]'),c('STRUKTURED LABS'),b'',
           c('[ ENGLISH SUBTITLES ]'),c('EADMASTER (RETROSUBS)'),c('SARA SCENARIO AND OPENING'),b'']
    if pad: lines=[l.ljust(31) if l else l for l in lines]
    ins(rolls[k],anchor,b'$$'+b'$'.join(lines)+b'$',after=False)
for r in rolls:
    for l in r.split(b'$'): assert l.lstrip(b'%').startswith((b'+',b'&')) or len(l.lstrip(b'%'))<=32, l
main=bytearray(6)+rolls[2]+rolls[0]
p2=6; p0=6+len(rolls[2]); p1=0xF740
assert len(main)<=0x1B02, hex(len(main))
assert len(rolls[1])<=0x10000-0xF740
assert all(x==0 for x in R[B+0xF740:B+0x10000])
main[0:6]=struct.pack('<3H',p0,p1,p2)
open(GEN+'/credits_main.bin','wb').write(main+bytes(0x1B02-len(main)))
open(GEN+'/credits_r1.bin','wb').write(rolls[1])
open(GEN+'/credits.asm','w').write(';; generated by tools/py/credits.py\norg $CA0000\nincbin "credits_main.bin"\norg $CAF740\nincbin "credits_r1.bin"\n')
print('credits: rolls %d/%d/%d bytes, main block %d of %d'%(len(rolls[0]),len(rolls[1]),len(rolls[2]),len(main),0x1B02))
