"""Derive font/en/glyphs_v2.txt (taller: cap 8px, x-height 6px, same advance widths) from glyphs.txt
by duplicating one straight-stroke row per glyph inside the cap/x-height zone (keeps line capacity unchanged)."""
import os
R=os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC=R+'/font/en/glyphs.txt'; DST=R+'/font/en/glyphs_v2.txt'
lines=open(SRC).read().split('\n'); out=[]; i=0
hdr='# Trinea EN VWF font v2 (generated by tools/py/font_v2.py from glyphs.txt): 11 rows, cap rows 0-7, descender 8-10.'
def grow(rows):
    body=rows[:7]; desc=rows[7:]
    ink=[r for r in range(7) if '#' in body[r]]
    if not ink: return ['.'*len(rows[0])]+rows
    top=ink[0]; mid=(top+6)/2
    eq=lambda r:(r>top and body[r]==body[r-1]) or (r<6 and body[r]==body[r+1])
    rng=[r for r in range(top,7) if '#' in body[r]]
    cands=[r for r in rng if eq(r) and '##' not in body[r]] or [r for r in rng if '##' not in body[r]] \
          or [r for r in rng if eq(r)] or [int(round(mid))]
    r=min(cands,key=lambda r:(abs(r-mid),r))
    body=body[:r+1]+[body[r]]+body[r+1:]
    return body+desc
out=[hdr]; g=None; rows=[]
def flush():
    if g is not None: out.append('== '+g); out.extend(grow(rows) if len(rows)==10 else rows)
for l in lines[1:]:
    if l.startswith('== '):
        flush(); g=l[3:]; rows=[]
    elif l and set(l)<=set('.#'): rows.append(l)
flush()
open(DST,'w').write('\n'.join(out)+'\n'); print('ok')
