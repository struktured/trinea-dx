#!/usr/bin/env python3
"""Pre-rendered English system text (shop, character select, money label).
The game draws these screens from lists of big-font glyph indices into a 2bpp strip buffer ($7F:F000,
64 bytes per 16x16 cell, tiles TL,TR,BL,BR) and shows messages with tilemap pieces. We render each English
line with the VWF font (font/en) into whole cells in Python, store the cells in bank $E6 as a private
'glyph font', point the two renderers' glyph fetch at $E6 and rewrite the glyph lists (+ shop tilemap pieces).
  char select: $C0:5633 LDA $C38000,x -> $E60000,x ; list $C0:56F0 (42 entries, same cell layout)
  shop:        $C0:6991 LDA $C38000,x -> $E60000,x ; lists via table $C0:75F8 ($75FC: 63 cells -> VRAM tiles 4+4k,
               $767C: 29 cells -> tiles $100+4k); message pieces via table $C0:7170 (9 msgs), rewritten in place
               in $C0:7182-$75F7; money label piece $C0:714A (cells 0-2) kept.
Input: script/en_system_layout.json. Output: build/gen/e6_sysglyphs.bin, build/gen/sys.asm"""
import json,struct,sys,os
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from paths import ROOT,GEN,FONT,ROM
R=open(ROM,'rb').read()
F=open(FONT+'/font.bin','rb').read(); W=open(FONT+'/widths.bin','rb').read()
L=json.load(open(ROOT+'/script/en_system_layout.json',encoding='utf-8'))
def width(s): return sum(W[ord(c)-0x20] for c in s)
def render(text,cells,align='left'):
    """-> list of 64-byte 2bpp cells"""
    px=[[0]*(cells*16) for _ in range(16)]
    w=width(text); assert w<=cells*16,(text,w,cells*16)
    pen=(cells*16-w)//2 if align=='center' else (1 if w<cells*16 else 0)
    for c in text:
        g=ord(c)-0x20
        for y in range(16):
            p0,p1=F[g*32+2*y],F[g*32+2*y+1]
            for x in range(8):
                v=((p0>>(7-x))&1)|(((p1>>(7-x))&1)<<1)
                if v and pen+x<cells*16: px[y][pen+x]=v
        pen+=W[g]
    out=[]
    for k in range(cells):
        cell=bytearray()
        for ty in (0,8):
            for tx in (0,8):
                for y in range(8):
                    p0=p1=0
                    for x in range(8):
                        v=px[ty+y][k*16+tx+x]; p0|=(v&1)<<(7-x); p1|=(v>>1)<<(7-x)
                    cell+=bytes([p0,p1])
        # order must be TL,TR,BL,BR
        out.append(bytes(cell))
    return out
def list_len(a):
    n=0
    while struct.unpack_from('<H',R,a+2*n)[0]!=0xFFFF: n+=1
    return n
bank=[]   # cells in $E6
def add(cells): i=len(bank); bank.extend(cells); return i
asm=[';; generated by sysgfx.py','org $C05633','    LDA.l $E60000,x','org $C06991','    LDA.l $E60000,x']
# ---- character select: same 42-cell layout as the JP list
cs=L['charselect']; assert list_len(0x56F0)==42
idx=[]
for e in cs:
    base=add(render(e['text'],e['cells'],e.get('align','left')))
    idx+=list(range(base,base+e['cells']))
while len(idx)<42: idx.append(add(render('',1))[0] if False else add(render('',1)))
asm.append('org $C056F0'); asm.append('    dw '+','.join('$%04X'%i for i in idx))
# ---- shop
n0,n1=list_len(0x75FC),list_len(0x767C); assert (n0,n1)==(63,29),(n0,n1)
slots=[]            # (list, pos) -> global cell index in bank
money=add(render(L['money_label']['text'],3,'center'))
lst0=[money,money+1,money+2]; lst1=[]
def tile_of(listno,pos): return (4+4*pos) if listno==0 else (0x100+4*pos)
pieces=[]
for m in L['shop_messages']:
    rec=[]
    for li,text in enumerate(m['lines']):
        cells=(width(text)+2+15)//16; assert cells<=12,(text,cells)
        cc=render(text,cells); b=add(cc)
        # put this line's cells in list0 if room else list1 (a line must not straddle lists)
        if len(lst0)+cells<=n0: lno=0; pos=len(lst0); lst0.extend(range(b,b+cells))
        else: lno=1; pos=len(lst1); lst1.extend(range(b,b+cells)); assert len(lst1)<=n1,'shop cell space'
        tiles=[tile_of(lno,pos+k) for k in range(cells)]
        row=3*li
        top=[0x2000|t|o for t in tiles for o in (0,1)]; bot=[0x2000|t|o for t in tiles for o in (2,3)]
        rec+=[row,4]+top+[0xFFFF]+[row+1,4]+bot+[0xFFFF]
    pieces.append(rec+[0xFFFF])
# write pieces into $C0:7182..$75F7 and repoint table $C0:7170
addr=0x7182; ptrs=[]; data=[]
for p in pieces: ptrs.append(addr+2*len(data)); data+=p
assert 0x7182+2*len(data)<=0x75F8,'shop piece space %d'%(2*len(data))
asm.append('org $C07170'); asm.append('    dw '+','.join('$%04X'%p for p in ptrs))
asm.append('org $C07182'); 
for i in range(0,len(data),16): asm.append('    dw '+','.join('$%04X'%x for x in data[i:i+16]))
lst0+= [lst0[-1]]*0; lst1+=[]
asm.append('org $C075FC'); asm.append('    dw '+','.join('$%04X'%i for i in lst0)+',$FFFF')
asm.append('org $C0767C'); asm.append('    dw '+','.join(['$%04X'%i for i in lst1]+['$FFFF']))
asm.append('org $E60000'); asm.append('    incbin "e6_sysglyphs.bin"')
assert len(bank)*64<=0x10000
open(GEN+'/e6_sysglyphs.bin','wb').write(b''.join(bank))
open(GEN+'/sys.asm','w').write('\n'.join(asm)+'\n')
print('sysgfx: %d cells, shop list0 %d/63 list1 %d/29, pieces %d bytes'%(len(bank),len(lst0),len(lst1),2*len(data)))
